import { spawnSync } from "child_process";
import {
  existsSync,
  mkdirSync,
  mkdtempSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from "fs";
import { join } from "path";
import { tmpdir } from "os";
import { afterEach, beforeEach, describe, expect, it } from "@jest/globals";

const CONFIG_KEYS_TO_CLEAR = [
  "SEMANTIC_SCHOLAR_API_KEY",
  "PAPER_SEARCH_UNPAYWALL_EMAIL",
  "UNPAYWALL_EMAIL",
  "CORE_API_KEY",
  "EASYSCHOLAR_KEY",
  "CROSSREF_MAILTO",
  "PAPER_SEARCH_CARSI_ENABLED",
  "GOOGLE_SCHOLAR_PROXY_URL",
  "SCHOLAR_RATE_LIMIT_RPS",
  "SCHOLAR_MAX_RETRIES",
  "SCHOLAR_TIMEOUT_MS",
];

describe("setup command", () => {
  let tempDir: string;
  let configFile: string;

  beforeEach(() => {
    tempDir = mkdtempSync(join(tmpdir(), "paper-search-setup-test-"));
    configFile = join(tempDir, "config.json");
  });

  afterEach(() => {
    rmSync(tempDir, { recursive: true, force: true });
  });

  it("auto-generates a random common email for missing Unpaywall and Crossref email prompts", () => {
    const result = runSetup("\n\n\n\n\n\n");

    expect(result.status).toBe(0);
    expect(result.stderr).toContain(
      "auto-generates a random Gmail-format address",
    );
    expect(result.stderr).toContain(
      "Get it at https://www.semanticscholar.org/product/api\nSEMANTIC_SCHOLAR_API_KEY",
    );
    expect(result.stderr).toContain(
      "Get it at https://www.easyscholar.cc/\nEASYSCHOLAR_KEY",
    );

    const output = JSON.parse(result.stdout);
    expect(output.updated).toEqual([
      "PAPER_SEARCH_UNPAYWALL_EMAIL",
      "CROSSREF_MAILTO",
    ]);
    expect(output.autoGenerated).toEqual([
      "PAPER_SEARCH_UNPAYWALL_EMAIL",
      "CROSSREF_MAILTO",
    ]);
    expect(output.skipped).toEqual([
      "SEMANTIC_SCHOLAR_API_KEY",
      "CORE_API_KEY",
      "EASYSCHOLAR_KEY",
      "PAPER_SEARCH_CARSI_ENABLED",
    ]);
    expect(
      output.capabilityProfile.entries.find(
        (entry: any) => entry.id === "entitled_access",
      ).readiness,
    ).toEqual({
      state: "disabled",
      code: "integration_disabled",
    });

    const config = readConfig();
    expect(config.PAPER_SEARCH_UNPAYWALL_EMAIL).toMatch(
      /^paper\.search\.[a-f0-9]{12}@gmail\.com$/,
    );
    expect(config.CROSSREF_MAILTO).toBe(config.PAPER_SEARCH_UNPAYWALL_EMAIL);
  });

  it("keeps existing email values when setup input is blank", () => {
    writeFileSync(
      configFile,
      JSON.stringify(
        {
          PAPER_SEARCH_UNPAYWALL_EMAIL: "real-user@example.org",
          CROSSREF_MAILTO: "contact@example.org",
        },
        null,
        2,
      ),
    );

    const result = runSetup("\n\n\n\n\n\n");

    expect(result.status).toBe(0);
    const output = JSON.parse(result.stdout);
    expect(output.kept).toEqual([
      "PAPER_SEARCH_UNPAYWALL_EMAIL",
      "CROSSREF_MAILTO",
    ]);
    expect(output.autoGenerated).toEqual([]);

    const config = readConfig();
    expect(config.PAPER_SEARCH_UNPAYWALL_EMAIL).toBe("real-user@example.org");
    expect(config.CROSSREF_MAILTO).toBe("contact@example.org");
  });

  it("installs the bundled skill when an explicit setup target is provided", () => {
    const result = runSetup("\n\n\n\n\n\n", [
      "--install-skills",
      "agents",
      "--skills-root",
      tempDir,
    ]);

    expect(result.status).toBe(0);
    const output = JSON.parse(result.stdout);
    expect(output.skills.skipped).toBe(false);
    expect(output.skills.destinations).toEqual([
      expect.objectContaining({
        target: "agents",
        path: join(tempDir, ".agents", "skills", "paper-search"),
      }),
    ]);
    expect(output.skills.result.installedCount).toBe(1);
    expect(
      existsSync(
        join(tempDir, ".agents", "skills", "paper-search", "SKILL.md"),
      ),
    ).toBe(true);
    expect(
      output.capabilityProfile.entries.find(
        (entry: any) => entry.id === "journal_metrics",
      ).requiredKeys,
    ).toEqual(["EASYSCHOLAR_KEY"]);
  });

  it("does not keep config setup as a duplicate setup entrypoint", () => {
    const result = runCli(["config", "setup", "--skip-skills"], "\n\n\n\n\n\n");

    expect(result.status).toBe(1);
    expect(result.stderr).toContain("Unknown config command: setup");
    expect(result.stdout).toContain('"code":"UNKNOWN_CONFIG_COMMAND"');
  });

  it("asks last whether to install school subscription downloads", () => {
    const result = runCli(["setup", "--skip-skills"], "\n\n\n\n\n\n\n", {
      HOME: tempDir,
      USERPROFILE: tempDir,
      LOCALAPPDATA: join(tempDir, "local"),
      XDG_DATA_HOME: join(tempDir, "xdg-data"),
    });

    expect(result.status).toBe(0);
    expect(result.stderr).toContain("Install school subscription downloads (CARSI)?");
    const output = JSON.parse(result.stdout);
    expect(output.carsi).toEqual({ installed: false, asked: true });
    expect(output.nextSteps.join(" ")).toContain("paper-search carsi install");
  });

  it("enables CARSI only for the exact value true and reports an absent executable without failing setup", () => {
    const result = runSetup("\n\n\n\n\ntrue\n", ["--skip-skills"], {
      PATH: join(tempDir, "empty-path"),
    });

    expect(result.status).toBe(0);
    const output = JSON.parse(result.stdout);
    expect(readConfig().PAPER_SEARCH_CARSI_ENABLED).toBe("true");
    expect(
      output.capabilityProfile.entries.find(
        (entry: any) => entry.id === "entitled_access",
      ),
    ).toEqual(
      expect.objectContaining({
        status: "unavailable",
        missing: ["carsi"],
        readiness: { state: "absent", code: "executable_missing" },
      }),
    );
    expect(result.stderr).toContain(
      "enter true only once it is installed",
    );
  });

  it("stores TRUE but keeps CARSI disabled because enablement is strict", () => {
    const marker = join(tempDir, "scan-marker.log");
    const binDir = join(tempDir, "bin");
    mkdirSync(binDir, { recursive: true });
    const executable = join(binDir, "paper-search-carsi");
    writeFileSync(
      executable,
      `#!/bin/sh\nprintf spawned >> ${JSON.stringify(marker)}\nexit 1\n`,
      { mode: 0o755 },
    );

    const result = runSetup("\n\n\n\n\nTRUE\n", ["--skip-skills"], {
      PATH: binDir,
    });

    expect(result.status).toBe(0);
    const output = JSON.parse(result.stdout);
    expect(readConfig().PAPER_SEARCH_CARSI_ENABLED).toBe("TRUE");
    expect(
      output.capabilityProfile.entries.find(
        (entry: any) => entry.id === "entitled_access",
      ).readiness,
    ).toEqual({
      state: "disabled",
      code: "integration_disabled",
    });
    expect(existsSync(marker)).toBe(false);
  });

  it("keeps an existing exact true value and probes CARSI exactly once", () => {
    const logPath = join(tempDir, "setup-carsi.log");
    const binDir = join(tempDir, "fake-bin");
    const executable = join(binDir, "paper-search-carsi");
    const fixturePath = join(
      process.cwd(),
      "tests/fixtures/carsi/fake/fake-carsi-mcp.mjs",
    );
    mkdirSync(binDir, { recursive: true });
    writeFileSync(
      configFile,
      JSON.stringify({ PAPER_SEARCH_CARSI_ENABLED: "true" }, null, 2),
    );
    writeFileSync(
      executable,
      `#!/bin/sh\nexec ${shellQuote(process.execPath)} ${shellQuote(fixturePath)} --scenario success --log ${shellQuote(logPath)} "$@"\n`,
      { mode: 0o755 },
    );

    const result = runSetup("\n\n\n\n\n\n", ["--skip-skills"], {
      PATH: binDir,
      XDG_DATA_HOME: join(tempDir, "xdg-data"),
    });

    expect(result.status).toBe(0);
    const output = JSON.parse(result.stdout);
    expect(output.kept).toContain("PAPER_SEARCH_CARSI_ENABLED");
    expect(
      output.capabilityProfile.entries.find(
        (entry: any) => entry.id === "entitled_access",
      ).readiness,
    ).toEqual({
      state: "available",
      code: "ready",
    });
    const events = readFileSync(logPath, "utf8")
      .trim()
      .split("\n")
      .map((line) => JSON.parse(line));
    expect(events.filter((event) => event.event === "start")).toHaveLength(1);
    expect(events.filter((event) => event.event === "call")).toEqual([]);
  });

  function runSetup(
    input: string,
    extraArgs: string[] = ["--skip-skills"],
    extraEnv: NodeJS.ProcessEnv = {},
  ) {
    // The extension question depends on this machine's install: asked by its own test.
    return runCli(["setup", ...extraArgs, "--skip-carsi"], input, extraEnv);
  }

  function runCli(
    args: string[],
    input = "",
    extraEnv: NodeJS.ProcessEnv = {},
  ) {
    const env: NodeJS.ProcessEnv = {
      ...process.env,
      PAPER_SEARCH_CONFIG_FILE: configFile,
      ...extraEnv,
    };
    for (const key of CONFIG_KEYS_TO_CLEAR) {
      delete env[key];
    }

    return spawnSync(
      process.execPath,
      [join(process.cwd(), "node_modules/.bin/tsx"), "src/cli.ts", ...args],
      {
        cwd: process.cwd(),
        env,
        input,
        encoding: "utf8",
      },
    );
  }

  function readConfig(): Record<string, string> {
    expect(existsSync(configFile)).toBe(true);
    return JSON.parse(readFileSync(configFile, "utf8")) as Record<
      string,
      string
    >;
  }
});

function shellQuote(value: string): string {
  return `'${value.replace(/'/g, `'"'"'`)}'`;
}
